// Task's public model retains the column types used by existing MySQL callers.
// The PostgreSQL provisioner keeps the same columns and uses native types.
const createPostgresTaskTable = `CREATE TABLE IF NOT EXISTS core_task (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	created_at timestamptz,
	updated_at timestamptz,
	deleted_at timestamptz,
	organization_id varchar(64) COLLATE "C" NOT NULL,
	user_id varchar(128) COLLATE "C" NOT NULL,
	subject_id bigint NOT NULL,
	step integer NOT NULL,
	task_type varchar(32) NOT NULL,
	priority smallint NOT NULL,
	task_status varchar(12) NOT NULL,
	redo integer NOT NULL,
	err_msg text,
	comment varchar(255),
	worker_id varchar(255),
	start_at timestamptz,
	end_at timestamptz,
	cost bigint,
	payload text,
	result text,
	app_group varchar(32),
	task_config_redo integer NOT NULL DEFAULT 0,
	task_config_timeout bigint NOT NULL DEFAULT 0
)`

// The index lookup uses the same search path as task queries. Include invalid
// indexes in the result so a broken or partial index cannot pass validation.
const postgresTaskIndexStatistics = `
SELECT index_relation.relname AS "INDEX_NAME",
       attribute.attname AS "COLUMN_NAME",
       CASE WHEN index_meta.indisunique THEN 0 ELSE 1 END AS "NON_UNIQUE",
       index_column.position AS "SEQ_IN_INDEX",
       CASE WHEN index_meta.indoption[(index_column.position - 1)::int] = 0 THEN 'A' ELSE 'D' END AS "COLLATION",
       upper(access_method.amname) AS "INDEX_TYPE",
       CASE WHEN index_meta.indisvalid AND index_meta.indisready AND index_meta.indislive
                 AND index_meta.indpred IS NULL AND index_meta.indnkeyatts = index_meta.indnatts
            THEN 'YES' ELSE 'NO' END AS "IS_VISIBLE"
FROM pg_catalog.pg_index AS index_meta
JOIN pg_catalog.pg_class AS index_relation ON index_relation.oid = index_meta.indexrelid
JOIN pg_catalog.pg_am AS access_method ON access_method.oid = index_relation.relam
CROSS JOIN LATERAL unnest(index_meta.indkey) WITH ORDINALITY AS index_column(attribute_number, position)
LEFT JOIN pg_catalog.pg_attribute AS attribute
       ON attribute.attrelid = index_meta.indrelid AND attribute.attnum = index_column.attribute_number
WHERE index_meta.indrelid = pg_catalog.to_regclass(?)
ORDER BY index_relation.relname, index_column.position`

func initPostgresTaskTable(db *gorm.DB) error {
	return db.Transaction(func(tx *gorm.DB) error {
		var exists bool
		if err := tx.Raw("SELECT pg_catalog.to_regclass(?) IS NOT NULL", TableNameCoreTask).Scan(&exists).Error; err != nil {
			return fmt.Errorf("locate core_task: %w", err)
		}
		if !exists {
			if err := tx.Exec(createPostgresTaskTable).Error; err != nil {
				return fmt.Errorf("create core_task: %w", err)
			}
		}
		var rows []Task
		if err := tx.Session(&gorm.Session{QueryFields: true}).Limit(0).Find(&rows).Error; err != nil {
			return fmt.Errorf("verify core_task columns: %w", err)
		}
		statistics, err := readTaskIndexStatistics(tx)
		if err != nil {
			return err
		}
		for _, name := range []string{tx.NamingStrategy.IndexName(TableNameCoreTask, "deleted_at"), "idx_core_task_member"} {
			columns, err := taskIndexColumns(tx, &Task{}, name)
			if err != nil {
				return err
			}
			exists, err := validateExactTaskIndex(name, columns, statistics)
			if err != nil {
				return err
			}
			if !exists {
				if err := createTaskIndex(tx, &Task{}, name); err != nil {
					return err
				}
			}
		}
		return ensureTaskIndexes(tx)
	})
}
